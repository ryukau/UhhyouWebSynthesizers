export const NOTE_NAMES = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"];
export const STANDARD_GUITAR_TUNING_MIDI = [40, 45, 50, 55, 59, 64];
export const STRING_SEMITONE_OFFSETS = [0, 5, 10, 15, 19, 24];

// Harmonic series approximation of open strings E-A-D-G-B-E from bass fundamental
export const HARMONIC_OPEN_HARMONICS = [16, 21, 28, 19, 24, 16];
export const HARMONIC_OPEN_OCTAVES = [0, 0, 0, 1, 1, 2];

/**
 * Returns nominal note name for a string and fret relative to bassPitchMidi.
 * @param {number} stringIdx - 0 (low string) to 5 (high string)
 * @param {number} fret - Fret number (0 = open)
 * @param {number} bassPitchMidi - Reference pitch of string 6 open
 * @returns {string} Note name
 */
export function getStringNoteName(stringIdx, fret, bassPitchMidi = 40) {
  const bassPitchClass = ((Math.round(bassPitchMidi) % 12) + 12) % 12;
  const pitchClass = (bassPitchClass + STRING_SEMITONE_OFFSETS[stringIdx] + fret) % 12;
  return NOTE_NAMES[(pitchClass + 12) % 12];
}

/**
 * Calculates sounding pitch in continuous MIDI semitones.
 * @param {number} tuningMode - 0 for 12-TET, 1 for Harmonic Series
 * @param {number} stringIdx - 0 (low E) to 5 (high E)
 * @param {number} fret - Fret number (0 = open)
 * @param {number} bassPitchMidi - Reference pitch of string 6 open (default 40 for E2)
 * @returns {number} Continuous MIDI pitch
 */
export function calculateStringPitch(tuningMode, stringIdx, fret, bassPitchMidi = 40) {
  if (tuningMode === 1) {
    const totalRatio
      = (HARMONIC_OPEN_HARMONICS[stringIdx] * (1 << HARMONIC_OPEN_OCTAVES[stringIdx]) * (16 + fret))
      / 256;
    return bassPitchMidi + 12 * Math.log2(totalRatio);
  }
  return bassPitchMidi + STRING_SEMITONE_OFFSETS[stringIdx] + fret;
}

