/**
 * Encodes 6 fret integers (-1 for muted, 0..24 for frets) into a 30-bit key.
 * @param {number[]} frets
 * @returns {number}
 */
export function encodeFrets(frets) {
  let key = 0;
  for (let i = 0; i < frets.length; i++) {
    const val = frets[i] < 0 ? 0 : frets[i] + 1;
    key |= (val & 0x1f) << (5 * i);
  }
  return key >>> 0;
}

/**
 * Normalizes absolute frets played on the guitar neck into relative fret positions.
 * @param {number[]} frets
 * @returns {number[]}
 */
export function toRelativeFrets(frets) {
  const played = frets.filter((f) => f >= 0);
  if (played.length === 0) return frets;

  const hasOpenStrings = played.some((f) => f === 0);
  const baseFret = hasOpenStrings ? 1 : Math.min(...played);

  return frets.map((f) => (f <= 0 ? f : f - baseFret + 1));
}

/**
 * Categorizes microtonal intonation deviation from 12-TET.
 * @param {number} centsDeviation
 * @returns {{symbol: string, level: string}}
 */
export function classifyIntonation(centsDeviation) {
  const abs = Math.abs(centsDeviation);
  if (abs < 6) return {symbol: "·", level: "clean"};
  if (abs < 20) { return {symbol: centsDeviation > 0 ? "↑" : "↓", level: "mild"}; }
  return {symbol: centsDeviation > 0 ? "⇈" : "⇊", level: "dissonant"};
}

/**
 * Resolves chord identity, global root offset in semitones, and per-string microtonal deviations.
 * @param {number[]} frets - 6-element array of played frets (-1 if muted).
 * @param {(number|null)[]} soundingPitches - Sounding MIDI pitch for each string (or null if
 *   muted).
 * @param {number} bassPitchMidi - Reference pitch of string 6 open (default 40 for E2).
 */
export function resolveChord(frets, soundingPitches, bassPitchMidi = 40) {
  const lowestStrIdx = frets.findIndex((f) => f >= 0);
  if (lowestStrIdx === -1) {
    return {
      chordName: "Muted",
      chordNameWithSemitones: "Muted",
      stringDeviations: [],
      hasDissonance: false,
    };
  }

  const lowestFret = frets[lowestStrIdx];
  const rootName = getStringNoteName(lowestStrIdx, lowestFret, bassPitchMidi);

  const packedKey = encodeFrets(toRelativeFrets(frets));
  const quality = chordTable[packedKey] ?? "custom";
  const chordName = quality === "major" ? `${rootName} major` : `${rootName} ${quality}`;

  const nominalRootPitch
    = Math.round(bassPitchMidi) + STRING_SEMITONE_OFFSETS[lowestStrIdx] + lowestFret;
  const soundingRootPitch = soundingPitches[lowestStrIdx] ?? nominalRootPitch;
  const globalOffsetSemitones = soundingRootPitch - nominalRootPitch;

  const roundedOffset = Math.round(globalOffsetSemitones * 1e3) / 1e3;
  const sign = roundedOffset >= 0 ? "+" : "-";
  const chordNameWithSemitones = `${chordName}, ${sign}${Math.abs(roundedOffset).toFixed(3)} st.`;

  const stringDeviations = [];
  let hasDissonance = false;

  for (let s = 0; s < frets.length; s++) {
    if (frets[s] < 0 || soundingPitches[s] == null) {
      stringDeviations.push({
        muted: true,
        noteName: "",
        symbol: "x",
        level: "clean",
      });
      continue;
    }

    const pitch = soundingPitches[s];
    const semitonesFromRoot = Math.round(pitch - soundingRootPitch);
    const deviationCents = (pitch - (soundingRootPitch + semitonesFromRoot)) * 100;
    const intonation = classifyIntonation(deviationCents);

    if (intonation.level !== "clean") hasDissonance = true;

    stringDeviations.push({
      muted: false,
      noteName: getStringNoteName(s, frets[s], bassPitchMidi),
      symbol: intonation.symbol,
      level: intonation.level,
    });
  }

  return {
    chordName,
    chordNameWithSemitones,
    stringDeviations,
    hasDissonance,
  };
}
